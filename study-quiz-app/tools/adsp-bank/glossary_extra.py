ALIASES = {"층화 추출법": ["층화 추출"], "계통 추출법": ["계통 추출"]}
EXACT = {}


def apply_aliases(entries):
    for e in entries:
        extra = ALIASES.get(e["term"])
        if extra:
            e["aliases"] = e["aliases"] + [a for a in extra if a not in e["aliases"]]
        ex = EXACT.get(e["term"])
        if ex:
            e["exact_aliases"] = e.get("exact_aliases", []) + ex


def find(entries, name, ctx=""):
    """이름(용어 또는 별칭)으로 용어 항목 찾기. 여러 개면 문제 문맥과 가까운 것"""
    import glossary

    key = glossary.compact(name).lower()
    hits = [e for e in entries if any(glossary.compact(a).lower() == key for a in e["aliases"] + e.get("exact_aliases", []))]
    if not hits:
        raise SystemExit(f"QT에 지정한 용어가 용어집에 없음: {name}")
    return max(hits, key=lambda e: glossary._closeness(e, ctx))


