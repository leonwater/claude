# 보기 문장은 강조된 용어를 그대로 쓰고, 틀린 문장은 강조된 용어끼리 바꿔 만든다.
#
# tf(과목, 단원, 개념, 주제, 종류, 문장들, 용어=())
#   종류: "옳은" 또는 "옳지 않은"
#   문장: (True, 옳은 문장, PDF 근거) 또는 (False, 틀린 문장, PDF 근거, 무엇이 틀렸는지)
#         PDF에 근거가 없는 임의의 틀린 문장은 (False, 문장, None, None) → 'PDF에 없는 선지입니다.'
#   정답이 아닌 보기의 설명(choiceInfo)은 여기서 바로 등록한다(옳은 문장은 "옳은 설명", 틀린 문장은 틀린 이유).
import glossary_extra
from choice_notes import n

Q = []


def tf(s, ch, c, topic, kind, items, terms=()):
    want = kind == "옳은"
    answers = [it for it in items if it[0] == want]
    assert len(items) == 4 and len(answers) == 1, c
    ans = answers[0]
    others = [it for it in items if it is not ans]
    if want:
        exp = "PDF에 적힌 내용과 같은 옳은 설명입니다."
    else:
        exp = f"틀린 설명입니다. {ans[3]}"
    Q.append(dict(s=s, ch=ch, c=c, q=f"{topic}에 대한 설명으로 {kind} 것은?", o=[ans[1]] + [it[1] for it in others],
                  e=exp, src=ans[2], img=None))
    for it in others:
        if it[2] is None:  # 임의로 만든 틀린 문장
            n(c, it[1], "PDF에 없는 선지입니다.", None)
        elif it[0]:
            n(c, it[1], "옳은 설명입니다(PDF 내용과 같음).", it[2])
        else:
            n(c, it[1], f"틀린 설명입니다. {it[3]}", it[2])
    if terms:
        glossary_extra.QT[c] = list(terms)


