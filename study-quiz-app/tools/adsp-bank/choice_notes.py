"""오답 선지 설명. 용어집에 없는 선지(숫자, 순서, 문장형 선지 등)에 대해 PDF 근거와 함께 적는다.

n(개념, 선지, 설명, 근거)   근거 "=" 는 그 문제의 근거 문장(sourceQuote)과 같다는 뜻이다.
nopdf(개념, 선지, ...)      PDF에 없는 선지(긴 선지는 make_bank.py가 PDF에 정말 없는지 확인한다)
"""
NOTES = {}


def n(concept, choice, note, quote="="):
    NOTES[(concept, choice)] = (note, quote)


def nopdf(concept, *choices):
    """PDF에 없는 선지(내가 오답으로 만든 선지). 설명 없이 '없음'으로만 표시한다"""
    for choice in choices:
        NOTES[(concept, choice)] = ("PDF에 없는 선지입니다.", None)


def many(concept, choices, text, quote="="):
    """같은 설명을 여러 선지에 붙인다. text 안의 {c}는 선지 글자로 바뀐다"""
    for c in choices:
        n(concept, c, text.format(c=c), quote)


